const fs = require("node:fs");
const path = require("node:path");

const MAX_URL_LENGTH = 2048;
const MAX_TEXT_LENGTH = 10000;
const MAX_HTML_LENGTH = 1024 * 1024;
const MAX_REQUEST_BYTES =
  2 * MAX_HTML_LENGTH * 6 + MAX_TEXT_LENGTH * 6 + MAX_URL_LENGTH * 6 + 16384;
const PORT = process.env.PORT ? Number(process.env.PORT) : 3004;

const DEFAULT_SERVICE_SETTINGS = Object.freeze({
  crawler: Object.freeze({ url: "http://localhost:3001", timeoutMs: 120000 }),
  textDetection: Object.freeze({
    url: "http://localhost:3000",
    timeoutMs: 5000,
  }),
  defacement: Object.freeze({ url: "http://localhost:3002", timeoutMs: 5000 }),
  linkDetection: Object.freeze({
    url: "http://localhost:3003",
    timeoutMs: 5000,
  }),
});

function resolveDefaultEnvPath() {
  if (process.env.AGGREGATOR_ENV_FILE && fs.existsSync(process.env.AGGREGATOR_ENV_FILE)) {
    return path.resolve(process.env.AGGREGATOR_ENV_FILE);
  }
  const candidates = [
    path.resolve(__dirname, "../../.env"),
    path.resolve(process.cwd(), "services/aggregator-service/.env"),
    path.resolve(process.cwd(), ".env"),
  ];
  for (const candidate of candidates) {
    if (fs.existsSync(candidate)) {
      return candidate;
    }
  }
  return path.resolve(__dirname, "../../.env");
}

function parseEnvFile(filePath) {
  if (!fs.existsSync(filePath)) {
    return {};
  }
  const content = fs.readFileSync(filePath, "utf8");
  const parsed = {};
  for (const rawLine of content.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eqIdx = line.indexOf("=");
    if (eqIdx <= 0) continue;
    const key = line.substring(0, eqIdx).trim();
    let val = line.substring(eqIdx + 1).trim();

    // Strip surrounding quotes if simple quoted value
    if (
      (val.startsWith('"') && val.endsWith('"') && val.indexOf('"', 1) === val.length - 1) ||
      (val.startsWith("'") && val.endsWith("'") && val.indexOf("'", 1) === val.length - 1)
    ) {
      val = val.slice(1, -1);
    }
    parsed[key] = val;
  }
  return parsed;
}

function loadAggregatorEnv(envFilePath, targetEnv = process.env, options = {}) {
  const filePath = envFilePath ? path.resolve(envFilePath) : resolveDefaultEnvPath();
  const fileVars = parseEnvFile(filePath);
  const override = options.override === true;

  for (const [key, val] of Object.entries(fileVars)) {
    const currentVal = targetEnv[key];
    const isBlank =
      currentVal === undefined ||
      currentVal === null ||
      (typeof currentVal === "string" && currentVal.trim() === "");

    if (override || isBlank) {
      targetEnv[key] = val;
    }
  }

  return targetEnv;
}

function normalizeServiceUrl(value, name) {
  let url;
  try {
    url = new URL(value);
  } catch {
    throw new TypeError(`${name} must be a valid HTTP or HTTPS URL.`);
  }

  if (
    (url.protocol !== "http:" && url.protocol !== "https:") ||
    url.username ||
    url.password ||
    url.search ||
    url.hash
  ) {
    throw new TypeError(
      `${name} must be an HTTP or HTTPS base URL without credentials.`,
    );
  }

  const basePath = url.pathname === "/" ? "" : url.pathname.replace(/\/+$/, "");
  return `${url.origin}${basePath}`;
}

function normalizeDashboardOrigin(value) {
  let url;
  try {
    url = new URL(value);
  } catch {
    throw new TypeError(
      "DASHBOARD_ORIGIN must be a valid HTTP or HTTPS origin.",
    );
  }

  if (
    (url.protocol !== "http:" && url.protocol !== "https:") ||
    url.username ||
    url.password ||
    url.pathname !== "/" ||
    url.search ||
    url.hash
  ) {
    throw new TypeError(
      "DASHBOARD_ORIGIN must be a valid HTTP or HTTPS origin.",
    );
  }

  return url.origin;
}

function readTimeout(environment, name, fallback) {
  const value =
    environment[name] === undefined ? fallback : Number(environment[name]);
  if (!Number.isSafeInteger(value) || value < 1) {
    throw new TypeError(`${name} must be a positive integer.`);
  }
  return value;
}

function readAuthConfig(environment) {
  const username = environment.ADMIN_USERNAME;
  const passwordHash = environment.ADMIN_PASSWORD_HASH;
  if (
    typeof username !== "string" ||
    username.trim().length === 0 ||
    username.length > 128
  ) {
    throw new TypeError("ADMIN_USERNAME must contain 1 to 128 characters.");
  }
  if (
    typeof passwordHash !== "string" ||
    !/^scrypt\$[a-f0-9]{32,128}\$[a-f0-9]{128}$/i.test(passwordHash)
  ) {
    throw new TypeError(
      "ADMIN_PASSWORD_HASH must be a scrypt hash generated by scripts/hash-admin-password.js.",
    );
  }

  const secureCookie =
    environment.AUTH_COOKIE_SECURE === undefined
      ? environment.NODE_ENV === "production"
      : environment.AUTH_COOKIE_SECURE;
  if (secureCookie !== true && secureCookie !== false) {
    if (secureCookie !== "true" && secureCookie !== "false") {
      throw new TypeError("AUTH_COOKIE_SECURE must be true or false.");
    }
  }

  return {
    username,
    passwordHash,
    secureCookie: secureCookie === true || secureCookie === "true",
  };
}

function readSmtpConfig(environment = process.env) {
  const host = typeof environment.SMTP_HOST === "string" ? environment.SMTP_HOST.trim() : "";
  const portRaw = environment.SMTP_PORT !== undefined && environment.SMTP_PORT !== "" ? Number(environment.SMTP_PORT) : 587;
  const port = Number.isInteger(portRaw) && portRaw > 0 && portRaw <= 65535 ? portRaw : 587;
  const secureRaw = environment.SMTP_SECURE;
  const secure = secureRaw === true || secureRaw === "true" || port === 465;
  const user = typeof environment.SMTP_USER === "string" ? environment.SMTP_USER.trim() : "";
  const pass = typeof environment.SMTP_PASS === "string" ? environment.SMTP_PASS : "";
  const from = typeof environment.EMAIL_FROM === "string" ? environment.EMAIL_FROM.trim() : "";
  const to = typeof environment.EMAIL_TO === "string" ? environment.EMAIL_TO.trim() : "";

  const missing = [];
  if (!host) missing.push("SMTP_HOST");
  if (!port) missing.push("SMTP_PORT");
  if (!user) missing.push("SMTP_USER");
  if (!pass) missing.push("SMTP_PASS");
  if (!to) missing.push("EMAIL_TO");

  const isConfigured = missing.length === 0;

  return {
    host,
    port,
    secure,
    user,
    pass,
    from: from || user,
    to,
    isConfigured,
    missing,
  };
}

function loadAggregatorConfig(environment = process.env) {
  // When environment is process.env, ensure .env is populated into process.env if missing
  if (environment === process.env) {
    loadAggregatorEnv(undefined, process.env, { override: false });
  }

  const port = environment.PORT === undefined ? PORT : Number(environment.PORT);
  if (!Number.isInteger(port) || port < 1 || port > 65535) {
    throw new TypeError("PORT must be an integer between 1 and 65535.");
  }

  return {
    port,
    databasePath: environment.DATABASE_PATH || undefined,
    dashboardOrigin: normalizeDashboardOrigin(
      environment.DASHBOARD_ORIGIN || "http://localhost:5173",
    ),
    auth: readAuthConfig(environment),
    smtp: readSmtpConfig(environment),
    services: {
      textDetection: {
        url: normalizeServiceUrl(
          environment.TEXT_DETECTION_URL ||
            DEFAULT_SERVICE_SETTINGS.textDetection.url,
          "TEXT_DETECTION_URL",
        ),
        timeoutMs: readTimeout(
          environment,
          "TEXT_DETECTION_TIMEOUT_MS",
          DEFAULT_SERVICE_SETTINGS.textDetection.timeoutMs,
        ),
      },
      crawler: {
        url: normalizeServiceUrl(
          environment.CRAWLER_SERVICE_URL ||
            DEFAULT_SERVICE_SETTINGS.crawler.url,
          "CRAWLER_SERVICE_URL",
        ),
        timeoutMs: readTimeout(
          environment,
          "CRAWLER_TIMEOUT_MS",
          DEFAULT_SERVICE_SETTINGS.crawler.timeoutMs,
        ),
      },
      defacement: {
        url: normalizeServiceUrl(
          environment.DEFACEMENT_SERVICE_URL ||
            DEFAULT_SERVICE_SETTINGS.defacement.url,
          "DEFACEMENT_SERVICE_URL",
        ),
        timeoutMs: readTimeout(
          environment,
          "DEFACEMENT_SERVICE_TIMEOUT_MS",
          DEFAULT_SERVICE_SETTINGS.defacement.timeoutMs,
        ),
      },
      linkDetection: {
        url: normalizeServiceUrl(
          environment.LINK_DETECTION_SERVICE_URL ||
            DEFAULT_SERVICE_SETTINGS.linkDetection.url,
          "LINK_DETECTION_SERVICE_URL",
        ),
        timeoutMs: readTimeout(
          environment,
          "LINK_DETECTION_SERVICE_TIMEOUT_MS",
          DEFAULT_SERVICE_SETTINGS.linkDetection.timeoutMs,
        ),
      },
    },
  };
}

